type Ctx = {
  lang: Lang;
  setLang: (l: Lang) => void;
  t: (k: string) => string;
  /** Translate a dynamic item field (name/category/region/craft/status) with original FR string as fallback */
  ti: (prefix: string, value: string) => string;
};
const I18nCtx = createContext<Ctx | null>(null);

