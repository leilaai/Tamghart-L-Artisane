export function I18nProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Lang>("fr");
  useEffect(() => {
    try {
      const saved = localStorage.getItem("tamghart_lang") as Lang | null;
      if (saved && base[saved]) setLangState(saved);
    } catch {}
  }, []);
  useEffect(() => {
    document.documentElement.lang = lang === "tif" ? "ber" : lang;
    document.documentElement.dir = lang === "ar" ? "rtl" : "ltr";
  }, [lang]);
  const setLang = useCallback((l: Lang) => {
    setLangState(l);
    try { localStorage.setItem("tamghart_lang", l); } catch {}
  }, []);
  const t = useCallback((k: string) => base[lang][k] ?? base.fr[k] ?? k, [lang]);
  const ti = useCallback((prefix: string, value: string) => {
    const key = `${prefix}.${value}`;
    return itemOverrides[lang][key] ?? value;
  }, [lang]);
  return <I18nCtx.Provider value={{ lang, setLang, t, ti }}>{children}</I18nCtx.Provider>;
}

export function useI18n() {
  const v = useContext(I18nCtx);
  if (!v) throw new Error("I18nProvider missing");
  return v;
}
